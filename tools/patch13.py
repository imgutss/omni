"""Fixes found by deploying to the real Vercel and Netlify accounts.

1. `POST https://api.vercel.com/v11/projects` rejects an `env` property:
   `400 Invalid request: should NOT have additional property 'env'`.
   Environment variables are already written right afterwards by `vercelSetEnv`
   (`POST /v9/projects/{id}/env`), so the property is simply dropped.

2. `POST https://api.netlify.com/api/v1/sites/{id}/deploys` answers
   `500 {"error":"no implicit conversion of String into Integer"}` as soon as the
   body carries `edge_functions`. Without that key the same digest deploy returns
   200. The generated `netlify.toml` already proxies the tunnel path with
   200-status redirects, and the edge function stays in the deploy as a
   netlify.toml-declared function, so the key is dropped from the API body.

3. New Netlify sites are created with `sso_login: true`, which puts **every**
   path behind a 401 "Login Redirect" wall — the bridge would be dead on arrival.
   `PATCH /sites/{id} {"sso_login": false}` clears it (verified: 401 -> 200 and
   the proxied panel HTML comes back).

Run: python3 tools/patch13.py
"""
import pathlib

ROOT = pathlib.Path('/home/user/omni')
p = ROOT / 'src' / 'bridges.js'
s = p.read_text(encoding='utf-8')

EDITS = [
    # 1. Vercel: no `env` on project creation
    ("""      installCommand: null,
      env: [{ key: 'BACKEND_URL', value: `https://${String(target).replace(/^https?:\\/\\//, '').replace(/\\/+$/, '')}`, type: ['production', 'preview', 'development'], target: ['production', 'preview', 'development'] }],
    }),""",
     """      installCommand: null,
      // `env` is not an accepted property here (400 "should NOT have additional
      // property `env`"); vercelSetEnv writes BACKEND_URL right after.
    }),"""),

    # 2. Netlify: no `edge_functions` in the deploy body
    ("""      files: digest,
      edge_functions: [{ function: 'relay', path: '/*' }],
      env: { BACKEND_URL: `https://${cleanTarget}` },""",
     """      files: digest,
      // `edge_functions` here makes Netlify answer 500 ("no implicit conversion of
      // String into Integer"); the relay ships as a netlify.toml-declared function.
      env: { BACKEND_URL: `https://${cleanTarget}` },"""),

    # 3a. the helper that lifts Netlify's login wall
    ("""export async function deployNetlifyBridge({ token, name = '', target, tunnelPath = '/', onProgress = null, waitMs = 5""",
     """/** Netlify turns SSO login on for new sites; every path then answers 401. */
async function netlifyAllowPublicAccess(token, siteId) {
  await nfetch(token, `/sites/${encodeURIComponent(siteId)}`, {
    method: 'PATCH',
    body: JSON.stringify({ sso_login: false }),
  }).catch(() => null);
}

export async function deployNetlifyBridge({ token, name = '', target, tunnelPath = '/', onProgress = null, waitMs = 5"""),

    # 3b. call it for a reused site and for a freshly created one
    ("""    const existing = await nfetch(token, `/sites/${encodeURIComponent(name)}`).catch(() => null);
    if (existing?.id) return { id: existing.id, name: existing.name, subdomain: existing.subdomain, created: false };""",
     """    const existing = await nfetch(token, `/sites/${encodeURIComponent(name)}`).catch(() => null);
    if (existing?.id) {
      await netlifyAllowPublicAccess(token, existing.id);
      return { id: existing.id, name: existing.name, subdomain: existing.subdomain, created: false };
    }"""),
    ("""  if (!site?.id) throw new Error('نتلیفای شناسهٔ سایت برنگرداند.');
  if (name && site.name !== name)""",
     """  if (!site?.id) throw new Error('نتلیفای شناسهٔ سایت برنگرداند.');
  await netlifyAllowPublicAccess(token, site.id);
  if (name && site.name !== name)"""),

    # 4. declare the edge-function directory the way the files are laid out
    ("""  return `# netlify.toml — generated by Omni · zero-compute proxy for the tunnel path only
[[redirects]]""",
     """  return `# netlify.toml — generated by Omni · zero-compute proxy for the tunnel path only
[functions]
  directory = "netlify/edge-functions"

[[redirects]]"""),
]

for old, new in EDITS:
    n = s.count(old)
    if n != 1:
        raise SystemExit(f'expected 1 occurrence, found {n} for: {old[:70]!r}')
    s = s.replace(old, new, 1)

p.write_text(s, encoding='utf-8')
print('patched src/bridges.js')
